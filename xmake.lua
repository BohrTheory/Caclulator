set_project("calculator")
set_version("0.1.0")
set_languages("c++17")
add_rules("mode.debug", "mode.release")
set_warnings("all", "error")
option("app")
    set_default(false)
    set_showmenu(true)
    set_description("Build Qt app against an immutable real Rust producer")
option_end()
option("qt_units")
    set_default(false)
    set_showmenu(true)
    set_description("Build widget units (Qt required, Rust not required)")
option_end()
option("rust_archive")
    set_showmenu(true)
    set_description("Absolute path to immutable calculator_core static archive")
option_end()
option("rust_native_links")
    set_showmenu(true)
    set_description("Comma separated native libraries from producer rustc evidence")
option_end()

target("calculator_client")
    set_kind("static")
    add_files("ui/src/adapter.cpp", "ui/src/controller.cpp")
    add_includedirs("include", "ui/src", {public = true})

target("client_units")
    set_kind("binary")
    add_deps("calculator_client")
    add_files("ui/tests/client_units.cpp")
    add_tests("client_units")

if has_config("app") then
    target("calculator")
        add_rules("qt.widgetapp")
        add_frameworks("QtWidgets")
        add_deps("calculator_client")
        add_files("ui/src/main.cpp", "ui/src/window.cpp")
        on_load(function (target)
            local archive = get_config("rust_archive")
            assert(archive and path.is_absolute(archive) and os.isfile(archive),
                "--rust_archive must name an existing immutable real producer archive")
            target:add("ldflags", archive, {force = true})
            local links = get_config("rust_native_links")
            if links then target:add("syslinks", table.unpack(links:split(","))) end
        end)
end
if has_config("qt_units") then
    target("widget_units")
        add_rules("qt.widgetapp")
        add_frameworks("QtWidgets", "QtTest")
        add_deps("calculator_client")
        add_files("ui/src/window.cpp", "ui/tests/widget_units.cpp")
        add_tests("widget_units")
end
